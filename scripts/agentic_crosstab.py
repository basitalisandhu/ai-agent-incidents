#!/usr/bin/env python3
"""Cross-tabulate the OWASP Top 10 for Agentic Applications mappings against the coded fields.

Reads incidents/*.json and writes docs/owasp-agentic-crosstab.md: how many events map to
each ASI category, which events map to none (by lens), which categories co-occur, and the
authority, channel_out, vector and outcome codes behind each category. Offline and
deterministic; standard library only.

    python3 scripts/agentic_crosstab.py              # write docs/owasp-agentic-crosstab.md
    python3 scripts/agentic_crosstab.py --check      # exit 1 if the committed file is stale
    python3 scripts/agentic_crosstab.py --stdout     # print instead of writing

The dataset is a convenience sample of public reports, so these are counts of coded
records, not estimates of how common anything is.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from itertools import combinations
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from records import RecordError, load_records  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
INCIDENTS = ROOT / "incidents"
OUT = ROOT / "docs" / "owasp-agentic-crosstab.md"

ASI = [
    ("ASI01", "Agent Goal Hijack"),
    ("ASI02", "Tool Misuse and Exploitation"),
    ("ASI03", "Identity and Privilege Abuse"),
    ("ASI04", "Agentic Supply Chain Vulnerabilities"),
    ("ASI05", "Unexpected Code Execution"),
    ("ASI06", "Memory and Context Poisoning"),
    ("ASI07", "Insecure Inter-Agent Communication"),
    ("ASI08", "Cascading Agent Failures"),
    ("ASI09", "Human-Agent Trust Exploitation"),
    ("ASI10", "Rogue Agents"),
]
FIELDS = ("authority", "channel_out", "vector", "outcome", "type")
LENSES = ("surface", "target", "weapon")


def load(incidents_dir: Path = INCIDENTS) -> list[dict]:
    return load_records(incidents_dir, require=("id", "date", "type", "lens", "vector", "authority", "channel_out", "outcome", "name"))


def asi(record: dict) -> list[str]:
    return sorted(record.get("mappings", {}).get("owasp_agentic", []))


def pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f}%" if d else "n/a"


def top(counter: Counter, k: int = 3) -> str:
    items = sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))[:k]
    return ", ".join(f"`{v}` {n}" for v, n in items) or "none"


def render(records: list[dict]) -> str:
    n = len(records)
    mapped = [r for r in records if asi(r)]
    unmapped = [r for r in records if not asi(r)]
    dates = sorted(r["date"] for r in records)
    out: list[str] = []
    w = out.append
    w("# OWASP Agentic Top 10 against the coded fields")
    w("")
    w("Generated by `scripts/agentic_crosstab.py` from `incidents/*.json`; do not edit by hand.")
    w("")
    w("Counts of coded records in a convenience sample of public reports. Mappings are the maintainer's "
      "reading of each primary source; an empty list means no confident mapping. An event can map to "
      "more than one category, so category rows do not sum to the event count.")
    w("")
    w("## Coverage")
    w("")
    w(f"- Events: **{n}** ({dates[0]} to {dates[-1]})")
    w(f"- Mapped to at least one ASI category: **{len(mapped)}** ({pct(len(mapped), n)})")
    w(f"- Mapped to none: **{len(unmapped)}** ({pct(len(unmapped), n)})")
    multi = sum(1 for r in mapped if len(asi(r)) > 1)
    w(f"- Mapped events with two or more categories: **{multi}** of {len(mapped)} ({pct(multi, len(mapped))})")
    w("")
    w("| lens | events | mapped | unmapped | mapped share |")
    w("|---|---:|---:|---:|---:|")
    for lens in LENSES:
        group = [r for r in records if r["lens"] == lens]
        m = sum(1 for r in group if asi(r))
        w(f"| `{lens}` | {len(group)} | {m} | {len(group) - m} | {pct(m, len(group))} |")
    w("")
    w("| year | events | mapped | mapped share |")
    w("|---|---:|---:|---:|")
    for year in sorted({r["date"][:4] for r in records}):
        group = [r for r in records if r["date"].startswith(year)]
        m = sum(1 for r in group if asi(r))
        w(f"| {year} | {len(group)} | {m} | {pct(m, len(group))} |")
    w("")
    w("## Events per category")
    w("")
    w("| id | category | events | share of mapped | incidents | disclosures | threat reports |")
    w("|---|---|---:|---:|---:|---:|---:|")
    for code, name in ASI:
        group = [r for r in mapped if code in asi(r)]
        t = Counter(r["type"] for r in group)
        w(f"| `{code}` | {name} | {len(group)} | {pct(len(group), len(mapped))} | {t['incident']} | "
          f"{t['vulnerability-disclosure']} | {t['threat-report']} |")
    w("")
    w("## What each category was coded as")
    w("")
    w("Top three codes per field for the events mapped to each category.")
    w("")
    w("| id | events | authority | channel_out | vector | outcome |")
    w("|---|---:|---|---|---|---|")
    for code, _ in ASI:
        group = [r for r in mapped if code in asi(r)]
        if not group:
            continue
        cells = [top(Counter(r[f] for r in group)) for f in ("authority", "channel_out", "vector", "outcome")]
        w(f"| `{code}` | {len(group)} | " + " | ".join(cells) + " |")
    w("")
    w("## Categories that co-occur")
    w("")
    pairs: Counter = Counter()
    for r in mapped:
        for a, b in combinations(asi(r), 2):
            pairs[(a, b)] += 1
    w("| pair | events |")
    w("|---|---:|")
    for (a, b), c in sorted(pairs.items(), key=lambda kv: (-kv[1], kv[0])):
        w(f"| `{a}` + `{b}` | {c} |")
    w("")
    w("## Authority held, by category")
    w("")
    auths = sorted({r["authority"] for r in records}, key=lambda a: (-sum(1 for r in records if r["authority"] == a), a))
    w("| id | " + " | ".join(f"`{a}`" for a in auths) + " |")
    w("|---|" + "---:|" * len(auths))
    for code, _ in ASI:
        group = [r for r in mapped if code in asi(r)]
        if not group:
            continue
        c = Counter(r["authority"] for r in group)
        w(f"| `{code}` | " + " | ".join(str(c[a]) for a in auths) + " |")
    w("")
    w("## Events mapped to no category")
    w("")
    w("| id | lens | vector | name |")
    w("|---|---|---|---|")
    for r in sorted(unmapped, key=lambda r: (LENSES.index(r["lens"]), r["id"])):
        w(f"| {r['id']} | `{r['lens']}` | `{r['vector']}` | {r['name']} |")
    w("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--incidents", type=Path, default=INCIDENTS)
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if --out differs from a fresh render")
    ap.add_argument("--stdout", action="store_true", help="print the Markdown instead of writing it")
    a = ap.parse_args(argv)
    try:
        text = render(load(a.incidents))
    except RecordError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if a.stdout:
        sys.stdout.write(text)
        return 0
    if a.check:
        current = a.out.read_text(encoding="utf-8") if a.out.exists() else ""
        if current != text:
            print(f"{a.out} is stale; run python3 scripts/agentic_crosstab.py", file=sys.stderr)
            return 1
        return 0
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out.relative_to(ROOT) if a.out.is_relative_to(ROOT) else a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
